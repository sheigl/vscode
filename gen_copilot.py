#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = [
#     "pyyaml",
# ]
# ///
"""
Translate the OpenCode customizations into GitHub Copilot (VS Code / Copilot
app) customizations, and apply them on this machine.

Source of truth: ~/.config/opencode
    agents/*.md          -> copilot/agents/<name>.agent.md
    commands/*.md        -> copilot/skills/<name>/SKILL.md   (slash commands)
    skills/<name>/       -> copilot/skills/<name>/           (copied whole)
    opencode.jsonc mcp   -> copilot/mcp-config.json

Two steps, mirroring gen_vscode_models.py:

    1. generate (default)  write the translated tree into ./copilot next to
       this script, then commit and push it. ./copilot is the tracked,
       shareable artifact.
    2. apply                copy ./copilot into ~/.copilot (or $COPILOT_HOME),
       removing files that a previous run generated and that no longer exist.

Translation is intentionally lossy:
    * agent `model` IDs are dropped: OpenCode provider/model IDs do not exist
      in Copilot, so the session's selected model applies.
    * agent `permissions` are approximated with the Copilot tool aliases
      (edit -> edit, shell -> execute, subagent -> agent); deny rules remove
      the matching alias.
    * command bodies keep their text, with `$ARGUMENTS`, `!`shell`` blocks and
      OpenCode `skill({...})` calls rewritten to plain instructions.
    * MCP `oauth: false` is dropped; Copilot's portable format has no such
      field.

Usage:
    uv run ~/.config/Code/User/gen_copilot.py [generate] [out_dir]
    uv run ~/.config/Code/User/gen_copilot.py apply [out_dir]
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
OPENCODE_DIR = Path(os.environ.get("OPENCODE_DIR", "~/.config/opencode")).expanduser()
DEFAULT_OUT = SCRIPT_DIR / "copilot"
MARKER = "<!-- generated by gen_copilot.py from ~/.config/opencode; edits are overwritten -->"

SKILL_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n?", re.S)

# Copilot's built-in tool aliases, in the order we emit them.
TOOL_ALIASES = ("read", "search", "web", "todo", "agent", "edit", "execute")
ACTION_TO_TOOL = {
    "read": "read",
    "search": "search",
    "web": "web",
    "todo": "todo",
    "subagent": "agent",
    "agent": "agent",
    "edit": "edit",
    "write": "edit",
    "shell": "execute",
    "execute": "execute",
}


def warn(msg: str) -> None:
    print(f"  ! {msg}", file=sys.stderr)


def parse_frontmatter(text: str) -> tuple[dict, str]:
    import yaml

    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}, text
    try:
        meta = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as exc:
        warn(f"bad frontmatter: {exc}")
        return {}, text
    if not isinstance(meta, dict):
        return {}, text
    return meta, text[m.end():]


def render(meta: dict, body: str) -> str:
    import yaml

    head = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1000)
    return f"---\n{head}---\n\n{MARKER}\n\n{body.lstrip()}"


def clean_name(value: str) -> str:
    name = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return name or "unnamed"


def agent_tools(meta: dict) -> list[str]:
    """Approximate OpenCode permissions with Copilot tool aliases."""
    rules = meta.get("permissions") or []
    if not isinstance(rules, list):
        return ["*"]
    denied: set[str] = set()
    for rule in rules:
        if not isinstance(rule, dict) or rule.get("effect") != "deny":
            continue
        action = str(rule.get("action") or "").lower()
        if action == "*":
            return []
        tool = ACTION_TO_TOOL.get(action)
        if tool:
            denied.add(tool)
    if not denied:
        return ["*"]
    return [tool for tool in TOOL_ALIASES if tool not in denied]


def rewrite_skill_calls(body: str) -> str:
    """OpenCode loads skills with a tool; Copilot loads them by name."""
    body = re.sub(
        r"call the `skill` tool with `name: [\"']([^\"']+)[\"']`",
        r"use the `\1` skill",
        body,
    )
    body = re.sub(
        r"load `([^`]+)` with the `skill` tool",
        r"load the `\1` skill",
        body,
    )
    return body


def convert_agent(path: Path, out: Path) -> str:
    meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
    body = rewrite_skill_calls(body)
    name = clean_name(path.stem)
    mode = str(meta.get("mode") or "primary").lower()

    front: dict = {
        "name": name,
        "description": str(meta.get("description") or f"OpenCode {mode} agent {path.stem}"),
        "target": "github-copilot",
        "tools": agent_tools(meta),
    }
    if mode == "subagent":
        front["user-invocable"] = False
        front["disable-model-invocation"] = False

    target = out / "agents" / f"{name}.agent.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(front, body), encoding="utf-8")
    return f"{name}.agent.md"


def convert_command(path: Path, out: Path) -> str:
    meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
    name = clean_name(path.stem)

    body = body.replace("$ARGUMENTS", "the request text")
    body = rewrite_skill_calls(body)
    body = re.sub(
        r"skill\(\{\s*name:\s*[\"']([^\"']+)[\"']\s*\}\)",
        r"the `\1` skill",
        body,
    )
    body = re.sub(
        r"!`([^`]+)`",
        r"run `\1` and use its output",
        body,
    )

    front: dict = {
        "name": name,
        "description": str(meta.get("description") or f"OpenCode command {path.stem}"),
    }
    if meta.get("argument-hint"):
        front["argument-hint"] = str(meta["argument-hint"])

    skill_dir = out / "skills" / name
    skill_dir.mkdir(parents=True, exist_ok=True)
    (skill_dir / "SKILL.md").write_text(render(front, body), encoding="utf-8")
    return name


def copy_skill(path: Path, out: Path) -> str:
    skill_md = path / "SKILL.md"
    if not skill_md.exists():
        warn(f"skill {path.name} has no SKILL.md; skipped")
        return ""
    name = clean_name(path.name)
    if name != path.name:
        warn(f"skill directory {path.name!r} is not a valid Copilot name; using {name!r}")

    target = out / "skills" / name
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(path, target)

    meta, body = parse_frontmatter((target / "SKILL.md").read_text(encoding="utf-8"))
    meta["name"] = name
    if not meta.get("description"):
        warn(f"skill {name} has no description; Copilot requires one")
        meta["description"] = f"OpenCode skill {name}"
    (target / "SKILL.md").write_text(render(meta, body), encoding="utf-8")
    return name


def mcp_servers(config_path: Path) -> dict:
    import yaml  # noqa: F401  (jsonc -> json is enough; keep dependency explicit)

    raw = config_path.read_text(encoding="utf-8")
    # Strip // line comments outside strings (opencode.jsonc allows them).
    lines = []
    for line in raw.splitlines():
        in_string = False
        escaped = False
        cut = len(line)
        i = 0
        while i < len(line):
            ch = line[i]
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = not in_string
            elif not in_string and line[i:i + 2] == "//":
                cut = i
                break
            i += 1
        lines.append(line[:cut])
    cfg = json.loads("\n".join(lines))

    mcp = cfg.get("mcp") or {}
    if not isinstance(mcp, dict):
        return {}

    found: dict = {}
    nested = mcp.get("servers")
    if isinstance(nested, dict):
        found.update(nested)
    for key, value in mcp.items():
        if key == "servers" or not isinstance(value, dict):
            continue
        if value.get("type") in ("local", "remote") or "command" in value or "url" in value:
            found[key] = value

    servers: dict = {}
    for key, value in found.items():
        if not isinstance(value, dict) or value.get("enabled") is False:
            continue
        if value.get("type") == "local" or "command" in value:
            command = value.get("command")
            if isinstance(command, str):
                command = command.split()
            if not command:
                warn(f"mcp {key}: local server without command; skipped")
                continue
            entry: dict = {"type": "stdio", "command": str(command[0]), "args": [str(a) for a in command[1:]]}
            env = value.get("environment") or value.get("env")
            if isinstance(env, dict) and env:
                entry["env"] = {str(k): str(v) for k, v in env.items()}
        elif value.get("url"):
            entry = {"type": "http", "url": str(value["url"])}
            headers = value.get("headers")
            if isinstance(headers, dict) and headers:
                entry["headers"] = {
                    str(k): re.sub(r"\{env:([A-Za-z_][A-Za-z0-9_]*)\}", r"${\1}", str(v))
                    for k, v in headers.items()
                }
        else:
            warn(f"mcp {key}: unrecognised server shape; skipped")
            continue
        entry["tools"] = ["*"]
        servers[key] = entry
    return servers


def generate(out: Path) -> int:
    if not OPENCODE_DIR.exists():
        warn(f"{OPENCODE_DIR} does not exist")
        return 1
    if out.exists():
        shutil.rmtree(out)
    (out / "agents").mkdir(parents=True)
    (out / "skills").mkdir(parents=True)

    agents = [convert_agent(p, out) for p in sorted((OPENCODE_DIR / "agents").glob("*.md"))]
    commands = [convert_command(p, out) for p in sorted((OPENCODE_DIR / "commands").glob("*.md"))]
    skills = [copy_skill(p, out) for p in sorted((OPENCODE_DIR / "skills").iterdir()) if p.is_dir()]
    skills = [s for s in skills if s]

    servers = mcp_servers(OPENCODE_DIR / "opencode.jsonc")
    (out / "mcp-config.json").write_text(
        json.dumps({"mcpServers": servers}, indent=2) + "\n", encoding="utf-8"
    )

    manifest = {"agents": sorted(agents), "skills": sorted(set(commands + skills)), "mcp": True}
    (out / ".generated.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"  agents   {len(agents)}")
    print(f"  skills   {len(manifest['skills'])} ({len(commands)} from commands, {len(skills)} copied)")
    print(f"  mcp      {len(servers)} server(s)")
    print(f"  wrote    {out}")

    return 0 if commit_and_push(out) else 1


def apply(out: Path) -> int:
    target = Path(os.environ.get("COPILOT_HOME", "~/.copilot")).expanduser()
    manifest_path = out / ".generated.json"
    if not manifest_path.exists():
        warn(f"{manifest_path} missing; run generate first")
        return 1
    new = json.loads(manifest_path.read_text(encoding="utf-8"))

    old_path = target / ".generated.json"
    old = json.loads(old_path.read_text(encoding="utf-8")) if old_path.exists() else {}

    (target / "agents").mkdir(parents=True, exist_ok=True)
    (target / "skills").mkdir(parents=True, exist_ok=True)

    # Remove files a previous run generated and that no longer exist.
    for name in old.get("agents", []):
        if name not in new.get("agents", []):
            stale = target / "agents" / name
            if stale.exists():
                stale.unlink()
    for name in old.get("skills", []):
        if name not in new.get("skills", []):
            stale = target / "skills" / name
            if stale.is_dir():
                shutil.rmtree(stale)

    for name in new.get("agents", []):
        shutil.copy2(out / "agents" / name, target / "agents" / name)
    for name in new.get("skills", []):
        src = out / "skills" / name
        dst = target / "skills" / name
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
    if new.get("mcp"):
        shutil.copy2(out / "mcp-config.json", target / "mcp-config.json")

    old_path.write_text(json.dumps(new, indent=2) + "\n", encoding="utf-8")
    print(f"  applied  {len(new.get('agents', []))} agent(s), "
          f"{len(new.get('skills', []))} skill(s), mcp-config.json -> {target}")
    return 0


def commit_and_push(target: Path) -> bool:
    repo = SCRIPT_DIR

    def git(*args: str) -> bool:
        result = subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True)
        if result.returncode != 0:
            print(f"git {' '.join(args)} failed:\n{result.stderr.strip()}", file=sys.stderr)
        return result.returncode == 0

    if not git("rev-parse", "--is-inside-work-tree"):
        print("Not a git repo, skipping commit/push.", file=sys.stderr)
        return False
    rel = os.path.relpath(target, repo)
    if not git("add", "-A", "--", rel):
        return False
    if not git("diff", "--cached", "--quiet"):
        if not git("commit", "-m", "update copilot customizations from opencode"):
            return False
    return git("push")


def main() -> int:
    args = [a for a in sys.argv[1:]]
    mode = "generate"
    if args and args[0] in ("generate", "apply"):
        mode = args.pop(0)
    out = Path(args[0]).expanduser() if args else DEFAULT_OUT
    if mode == "apply":
        return apply(out)
    return generate(out)


if __name__ == "__main__":
    raise SystemExit(main())
